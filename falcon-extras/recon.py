"""Auto-extracted tool implementations.

See ``server.py`` ``@mcp.tool()`` wrappers for the public docstrings;
these are the worker functions they delegate to.
"""

from __future__ import annotations

import re
from typing import Any
from falcon_helpers import (
    _RECON_DOMAIN_RX,
    _RECON_EMAIL_RX,
    _RECON_FREETEXT_RX,
    _check_response,
    _get_recon_client,
    _project_exposed_record,
    _project_notification,
)
from falcon_helpers import swallow_exc

def recon_list_rules(limit: int = 50) -> dict[str, Any]:
    """List active Falcon Adversary Intelligence Recon monitoring rules. Read-only.
    Returns each rule's id, name, topic, filter, status, priority, and timestamps.
    Use this to understand what the tenant is already watching for so you don't
    propose redundant coverage.

    Args:
        limit: Max rules to return (1-500). Default 50.
    """
    try:
        recon = _get_recon_client()
        capped = min(max(limit, 1), 500)
        # NB: Recon's allowed sort fields are created_timestamp /
        # last_updated_timestamp / permissions / priority / template_priority
        # / topic. `updated_timestamp` (without the `last_` prefix) is
        # rejected with a 400. Without _check_response that 400 silently
        # surfaced as zero results.
        q = recon.query_rules(
            parameters={"limit": capped, "sort": "last_updated_timestamp|desc"}
        )
        guard = _check_response(q, "Recon")
        if guard:
            return guard
        body = q.get("body", {}) if isinstance(q, dict) else {}
        ids = body.get("resources") or []
        if not ids:
            return {"ok": True, "items": [], "count": 0}
        d = recon.get_rules(ids=ids)
        dguard = _check_response(d, "Recon")
        if dguard:
            return dguard
        items = (d.get("body", {}) if isinstance(d, dict) else {}).get("resources") or []
        return {"ok": True, "items": items, "count": len(items)}
    except Exception as exc:
        return swallow_exc(exc)


def recon_search_notifications(
    q: str | None = None, limit: int = 50
) -> dict[str, Any]:
    """Free-text search across Recon notifications already generated by tenant
    monitoring rules. The Recon corpus surfaces dark-web forum mentions,
    Telegram channel posts, paste-site dumps, breach-source leaks, and
    typosquat / brand-impersonation domains. Read-only.

    Note: this only returns matches against rules that already exist in the
    tenant. For ad-hoc lookup against the full Recon data lake, see
    extras_recon_search_exposed_records (which queries the credential-exposure
    corpus directly without requiring a pre-existing rule).

    Args:
        q: Free-text query (matches across all indexed notification fields).
        limit: Max notifications to return (1-500). Default 50.
    """
    try:
        if q is not None and not _RECON_FREETEXT_RX.fullmatch(q):
            return {
                "ok": False,
                "error": "q contains characters outside the allowed set [A-Za-z0-9 ._%+@:/-] or exceeds 200 chars",
            }
        recon = _get_recon_client()
        capped = min(max(limit, 1), 500)
        params: dict[str, Any] = {"limit": capped, "sort": "created_date|desc"}
        if q:
            params["q"] = q
        qr = recon.query_notifications(parameters=params)
        guard = _check_response(qr, "Recon")
        if guard:
            return guard
        body = qr.get("body", {}) if isinstance(qr, dict) else {}
        ids = body.get("resources") or []
        if not ids:
            return {"ok": True, "items": [], "count": 0, "query": q}
        d = recon.get_notifications_detailed(ids=ids)
        dguard = _check_response(d, "Recon")
        if dguard:
            return dguard
        raw = (d.get("body", {}) if isinstance(d, dict) else {}).get("resources") or []
        items = [_project_notification(r) for r in raw]
        return {"ok": True, "items": items, "count": len(items), "query": q}
    except Exception as exc:
        return swallow_exc(exc)


def recon_search_exposed_records(
    query: str,
    kind: str = "domain",
    limit: int = 50,
) -> dict[str, Any]:
    """Search the Recon exposed-data-records corpus (leaked credentials from
    breach dumps, paste sites, dark-web markets) by domain or email. Read-only.

    This is the primary tool for "are any of our users' credentials in known
    breaches" workflows. Unlike search_notifications, this queries the full
    credential-exposure corpus directly and does not require a pre-existing
    monitoring rule.

    Args:
        query: The value to search for. Strict per `kind`:
            - domain: lowercase hostname/registrable-domain (e.g. 'example.com')
            - email: full address (e.g. 'analyst@example.com')
            - free: free-text fallback (limited charset; see kind below).
        kind: 'domain' | 'email' | 'free'. Default 'domain'.
        limit: Max records to return (1-500). Default 50.
    """
    try:
        kind_norm = (kind or "domain").lower()
        norm_query = (query or "").strip()
        if not norm_query:
            return {"ok": False, "error": "query must be non-empty"}
        if kind_norm == "domain":
            v = norm_query.lower()
            if not _RECON_DOMAIN_RX.fullmatch(v):
                return {"ok": False, "error": f"invalid domain: {query!r}"}
            fql = f"domain:'{v}'"
        elif kind_norm == "email":
            v = norm_query.lower()
            if not _RECON_EMAIL_RX.fullmatch(v):
                return {"ok": False, "error": f"invalid email: {query!r}"}
            fql = f"email:'{v}'"
        elif kind_norm == "free":
            if not _RECON_FREETEXT_RX.fullmatch(norm_query):
                return {
                    "ok": False,
                    "error": "free-text query contains characters outside [A-Za-z0-9 ._%+@:/-] or exceeds 200 chars",
                }
            fql = None
        else:
            return {
                "ok": False,
                "error": f"unknown kind {kind!r} (expected domain|email|free)",
            }
        recon = _get_recon_client()
        capped = min(max(limit, 1), 500)
        params: dict[str, Any] = {"limit": capped, "sort": "exposure_date|desc"}
        if fql is not None:
            params["filter"] = fql
        else:
            params["q"] = norm_query
        qr = recon.query_notifications_exposed_data_records(parameters=params)
        guard = _check_response(qr, "Recon")
        if guard:
            return guard
        body = qr.get("body", {}) if isinstance(qr, dict) else {}
        ids = body.get("resources") or []
        if not ids:
            return {
                "ok": True,
                "items": [],
                "count": 0,
                "query": norm_query,
                "kind": kind_norm,
            }
        d = recon.get_notifications_exposed_data_records(ids=ids)
        dguard = _check_response(d, "Recon")
        if dguard:
            return dguard
        raw = (d.get("body", {}) if isinstance(d, dict) else {}).get("resources") or []
        items = [_project_exposed_record(r) for r in raw]
        return {
            "ok": True,
            "items": items,
            "count": len(items),
            "query": norm_query,
            "kind": kind_norm,
        }
    except Exception as exc:
        return swallow_exc(exc)


def recon_preview_corpus_search(
    query: str,
    kind: str = "domain",
) -> dict[str, Any]:
    """Search the full Falcon Adversary Intelligence Recon data lake for any
    mention of a domain, email, IP, or keyword — across criminal marketplaces,
    forums, public repos (GitHub paste-leaks), Telegram channels, social media,
    and breach dumps. Read-only.

    This is the right tool when the operator is asking "is anyone talking
    about us anywhere on the underground" — it queries the underlying corpus
    directly rather than tenant-scoped notifications, so it returns hits even
    when the tenant has no monitoring rules in place.

    The Recon API exposes this through the rule-preview endpoint: it returns
    aggregate counts by `channel` (criminal_marketplace / forum / public_repo /
    chat_medium / social_media) and by `site` (specific source like
    breachforums.cz, telegram.org, github.com). Raw items are NOT returned —
    that is by design from CrowdStrike. Counts + breakdown are the surface.

    Args:
        query: The value to search for. Strict per `kind`:
            - domain: registrable hostname (e.g. 'bankofamerica.com')
            - email: full address (e.g. 'analyst@example.com')
            - ip: IPv4 address (e.g. '203.0.113.1')
            - keyword: free-text brand string or VIP name; broadest topic
        kind: 'domain' | 'email' | 'ip' | 'keyword'. Default 'domain'.
    """
    try:
        kind_norm = (kind or "domain").lower()
        norm_query = (query or "").strip()
        if not norm_query:
            return {"ok": False, "error": "query must be non-empty"}

        if kind_norm == "domain":
            v = norm_query.lower()
            if not _RECON_DOMAIN_RX.fullmatch(v):
                return {"ok": False, "error": f"invalid domain: {query!r}"}
            topic = "SA_DOMAIN"
            fql = f"domain:'{v}'"
        elif kind_norm == "email":
            v = norm_query.lower()
            if not _RECON_EMAIL_RX.fullmatch(v):
                return {"ok": False, "error": f"invalid email: {query!r}"}
            topic = "SA_EMAIL"
            fql = f"email:'{v}'"
        elif kind_norm == "ip":
            # IPv4 only for v1; Recon's SA_IP topic enforces a strict format.
            if not re.fullmatch(r"^(?:(?:25[0-5]|2[0-4]\d|1?\d?\d)\.){3}(?:25[0-5]|2[0-4]\d|1?\d?\d)$", norm_query):
                return {"ok": False, "error": f"invalid IPv4: {query!r}"}
            topic = "SA_IP"
            fql = f"ip:'{norm_query}'"
        elif kind_norm == "keyword":
            if not _RECON_FREETEXT_RX.fullmatch(norm_query):
                return {
                    "ok": False,
                    "error": "keyword contains characters outside [A-Za-z0-9 ._%+@:/-] or exceeds 200 chars",
                }
            topic = "SA_CUSTOM"
            fql = f"keyword:'{norm_query}'"
        else:
            return {
                "ok": False,
                "error": f"unknown kind {kind!r} (expected domain|email|ip|keyword)",
            }

        recon = _get_recon_client()
        r = recon.preview_rule(body={"topic": topic, "filter": fql})
        # Route through _check_response so a 401/403 surfaces as the
        # staged-build scope_pending payload (consistent with the other
        # Recon tools), not a raw FalconPy error envelope.
        guard = _check_response(r, "Recon")
        if guard:
            return guard
        body = r.get("body", {}) if isinstance(r, dict) else {}

        # Resources is a list of named buckets; reshape into a flat result the
        # agent can table directly. Drop empty / unknown bucket names.
        resources = body.get("resources") or []
        total = 0
        channels: list[dict[str, Any]] = []
        sites: list[dict[str, Any]] = []
        for bucket in resources:
            name = bucket.get("name")
            buckets = bucket.get("buckets") or []
            if name == "count":
                if buckets:
                    total = int(buckets[0].get("count") or 0)
            elif name == "channel":
                channels = [
                    {"label": b.get("label"), "count": int(b.get("count") or 0)}
                    for b in buckets
                ]
            elif name == "site":
                sites = [
                    {"label": b.get("label"), "count": int(b.get("count") or 0)}
                    for b in buckets
                ]

        return {
            "ok": True,
            "query": norm_query,
            "kind": kind_norm,
            "topic": topic,
            "total_hits": total,
            "channels": channels,
            "top_sites": sites,
        }
    except Exception as exc:
        return swallow_exc(exc)

