#!/usr/bin/env node
// Writes licenses/THIRD-PARTY-NOTICES.txt: the license text of every
// production npm dependency (from package-lock.json + node_modules) and,
// with --python <interpreter>, every Python distribution installed in the
// eyas-mcp server's environment (the bundle ships them as wheels).
//
//   npm ci
//   PY=$(uvx --from "git+<mcp-server-git>@<mcp-server-ref>" python -c 'import sys; print(sys.executable)')
//   node scripts/gen-third-party-notices.mjs --python "$PY"
//
// Re-run after changing dependencies. Packages whose files aren't installed
// on this platform (other-OS optional binaries) are listed with the license
// recorded in the lockfile.

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const root = process.cwd();
const out = path.join(root, "licenses", "THIRD-PARTY-NOTICES.txt");
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;

function licenseTexts(dir) {
  let names;
  try {
    names = fs.readdirSync(dir);
  } catch {
    return [];
  }
  return names
    .filter((n) => LICENSE_FILE.test(n))
    .sort()
    .map((n) => {
      try {
        return fs.readFileSync(path.join(dir, n), "utf8").trim();
      } catch {
        return null;
      }
    })
    .filter(Boolean);
}

const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8"));
const seen = new Map();
for (const [key, entry] of Object.entries(lock.packages)) {
  if (!key || entry.dev || entry.link) continue;
  const name = entry.name ?? key.split("node_modules/").pop();
  const id = `${name}@${entry.version}`;
  if (seen.has(id)) continue;
  const dir = path.join(root, key);
  let license = entry.license;
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    license = pkg.license ?? license;
  } catch {
    // not installed on this platform
  }
  seen.set(id, { id, license: license ?? "UNKNOWN", texts: licenseTexts(dir) });
}

const sections = [...seen.values()].sort((a, b) => a.id.localeCompare(b.id));

const pyIdx = process.argv.indexOf("--python");
let pySections = [];
if (pyIdx !== -1) {
  const py = process.argv[pyIdx + 1];
  const code = String.raw`
import json, importlib.metadata as md
out = []
for d in md.distributions():
    name = d.metadata["Name"]
    if name in ("pip", "setuptools", "wheel"):
        continue
    lic = d.metadata.get("License-Expression") or d.metadata.get("License") or ""
    if len(lic) > 80 or not lic:
        lic = ", ".join(c.split(" :: ")[-1] for c in (d.metadata.get_all("Classifier") or []) if c.startswith("License ::")) or lic[:80] or "UNKNOWN"
    texts = []
    for f in d.files or []:
        base = f.name.lower()
        if base.startswith(("license", "licence", "copying", "notice")):
            try:
                texts.append(f.locate().read_text(encoding="utf-8").strip())
            except Exception:
                pass
    out.append({"id": f"{name}=={d.version}", "license": lic, "texts": texts})
print(json.dumps(out))
`;
  pySections = JSON.parse(execFileSync(py, ["-c", code], { encoding: "utf8" }))
    .sort((a, b) => a.id.toLowerCase().localeCompare(b.id.toLowerCase()));
}

const rule = "=".repeat(78);
const render = (s) =>
  [rule, `${s.id}  (${s.license})`, rule, s.texts.length ? s.texts.join("\n\n---\n\n") : "(license text not included in the installed package)", ""].join("\n");

const body = [
  "Third-party notices for Eyas",
  "",
  "Eyas is MIT-licensed (see LICENSE). It bundles or installs the components",
  "below, each under its own license. Bundled fonts: see licenses/fonts/.",
  "Generated by scripts/gen-third-party-notices.mjs; do not edit by hand.",
  "Python packages are those installed with the pinned eyas-mcp server",
  "(versions.json) on the machine that generated this file; a few are",
  "platform-specific (for example pywin32 is installed only on Windows).",
  "",
  `npm production dependencies (${sections.length})`,
  "",
  ...sections.map(render),
  ...(pySections.length
    ? [`Python dependencies of the eyas-mcp server (${pySections.length})`, "", ...pySections.map(render)]
    : []),
].join("\n");

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body.replace(/\r\n/g, "\n"));
console.log(`wrote ${path.relative(root, out)}: ${sections.length} npm, ${pySections.length} Python`);
