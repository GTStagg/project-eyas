#!/usr/bin/env bash
# Packages the falcon-mcp frontend into a distributable zip for standalone
# (non-Docker) macOS deployment. Run from the project root: ./make-dist.sh
#
# The resulting zip contains a Next.js standalone build + start.sh + .env.example
# + STANDALONE.md. End user only needs Node 20+ and uv on their Mac.
set -euo pipefail

GREEN='\033[0;32m'; BOLD='\033[1m'; DIM='\033[2m'; RESET='\033[0m'
step() { echo -e "  ${BOLD}$*${RESET}"; }
ok()   { echo -e "  ${GREEN}✓${RESET} $*"; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

VERSION=$(node -e "process.stdout.write(require('./package.json').version)")
BUNDLE_NAME="project-eyas-v${VERSION}"

# Pinned versions for the standalone bundle — the same pins dev spawns from
# (versions.json). Bump deliberately; `npm run upgrade-mcp` re-resolves dev.
PIN_FALCON_MCP=$(node -e "process.stdout.write(require('./versions.json')['mcp-server'])")
PIN_FALCON_MCP_PKG=$(node -e "process.stdout.write(require('./versions.json')['mcp-server-package'])")
PIN_FALCON_MCP_GIT=$(node -e "process.stdout.write(require('./versions.json')['mcp-server-git'])")
PIN_FALCON_MCP_REF=$(node -e "process.stdout.write(require('./versions.json')['mcp-server-ref'])")
# Network overlay: on hosts behind a package mirror, internal/build.env sets
# PIP_INDEX_URL / PIP_TRUSTED_HOST / PIP_CONSTRAINT and may redefine
# fetch_prebuild (below). Absent (public checkout) → PyPI + direct GitHub.
if [ -f "$SCRIPT_DIR/internal/build.env" ]; then
  # shellcheck disable=SC1091
  . "$SCRIPT_DIR/internal/build.env"
fi
GIT_SHA=$(git rev-parse --short HEAD 2>/dev/null || echo "unknown")
GIT_DIRTY=""
# --porcelain covers tracked changes AND untracked files (a not-yet-added module
# would otherwise be stamped as a clean, reproducible commit).
if [ -n "$(git status --porcelain 2>/dev/null)" ]; then
  GIT_DIRTY="-dirty"
fi
BUILD_TIMESTAMP=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
NODE_VERSION=$(node --version)
OUT_DIR="/tmp/${BUNDLE_NAME}-build-$$"
STAGE="${OUT_DIR}/${BUNDLE_NAME}"
ZIP_PATH="${SCRIPT_DIR}/${BUNDLE_NAME}.zip"

echo ""
# ─── Bake build-time deployment flags into the bundle ────────────────────────
# build-flags.ts ships with dev-mode defaults (no lock) so `npm run dev`
# stays fully editable. For the standalone build we overwrite the file
# with locked values BEFORE `npm run build`, then restore the original
# afterward so git stays clean. The locked values get compiled into the
# Next.js bundle — there's no runtime knob to flip them off.
# The gateway lock is opt-in: set ANTHROPIC_GATEWAY_BASE_URL to bake a
# gateway-only bundle. Without it the bundle accepts a direct Anthropic API
# key or a gateway URL entered on first run, like the dev server.
GATEWAY_URL="${ANTHROPIC_GATEWAY_BASE_URL:-}"
if [ -n "$GATEWAY_URL" ]; then
  GATEWAY_ONLY=true
  GATEWAY_LITERAL="\"${GATEWAY_URL}\""
else
  GATEWAY_ONLY=false
  GATEWAY_LITERAL="null"
fi
BUILD_FLAGS_PATH="lib/config/build-flags.ts"
BUILD_FLAGS_BACKUP="${OUT_DIR}.build-flags.bak"
mkdir -p "$(dirname "$BUILD_FLAGS_BACKUP")" 2>/dev/null || true
cp "$BUILD_FLAGS_PATH" "$BUILD_FLAGS_BACKUP"
restore_build_flags() {
  if [ -f "$BUILD_FLAGS_BACKUP" ]; then
    cp "$BUILD_FLAGS_BACKUP" "$BUILD_FLAGS_PATH"
    rm -f "$BUILD_FLAGS_BACKUP"
  fi
}
trap restore_build_flags EXIT

step "Baking deployment flags (gatewayOnly=${GATEWAY_ONLY}, forcedGatewayUrl=${GATEWAY_URL:-none})…"
cat > "$BUILD_FLAGS_PATH" <<EOF
import "server-only";

// Generated by make-dist.sh — DO NOT EDIT in this build. Restored from
// backup by the build script after \`npm run build\` completes.
export const BUILD_FLAGS = {
  gatewayOnly: ${GATEWAY_ONLY} as boolean,
  forcedGatewayUrl: ${GATEWAY_LITERAL} as string | null,
} as const;
EOF
ok "deployment flags baked"

step "Building Next.js standalone bundle…"
npm run build --silent
ok "build complete"

restore_build_flags
trap - EXIT

step "Staging files…"
rm -rf "$OUT_DIR"
mkdir -p "$STAGE"

# Next.js standalone output is a self-contained server tree at
# .next/standalone/. When Next detects a workspace root above the project
# (e.g. a parent package.json), the actual server.js is nested one directory
# deeper. Detect both layouts.
if [ -f .next/standalone/server.js ]; then
  STANDALONE_ROOT=".next/standalone"
elif [ -f .next/standalone/$(basename "$SCRIPT_DIR")/server.js ]; then
  STANDALONE_ROOT=".next/standalone/$(basename "$SCRIPT_DIR")"
else
  echo "  ERROR: could not locate server.js inside .next/standalone/" >&2
  exit 1
fi

# Copy the standalone root (server.js + .next/ + node_modules/ + …) flat into
# the bundle. node_modules from the workspace root, if any, also need to come
# along — they live at .next/standalone/node_modules and are required by the
# nested server.js.
cp -R "$STANDALONE_ROOT"/. "$STAGE/"
if [ "$STANDALONE_ROOT" != ".next/standalone" ] && [ -d .next/standalone/node_modules ]; then
  # Workspace-hoisted deps — merge without clobbering project-local deps.
  cp -Rn .next/standalone/node_modules/. "$STAGE/node_modules/" 2>/dev/null || true
fi
# Next's standalone output copies the builder's .env* files. Never ship them:
# .env holds AUTH_SESSION_SECRET (session + credential-encryption key) and
# any credentials. Also drop a local data/ directory if one was traced in.
find "$STAGE" -maxdepth 1 -name '.env*' ! -name '.env.example' -exec rm -f {} +
rm -rf "$STAGE/data"
mkdir -p "$STAGE/.next"
cp -R .next/static "$STAGE/.next/static"
if [ -d public ]; then
  cp -R public "$STAGE/public"
fi
ok "Next.js standalone server staged ($STANDALONE_ROOT)"

# Launcher + env template + docs
cp start.sh           "$STAGE/start.sh"
cp .env.example       "$STAGE/.env.example"
cp docs/STANDALONE.md "$STAGE/README.md"
# Project and third-party license notices (fonts, npm and Python deps).
cp LICENSE NOTICE.md  "$STAGE/"
cp -R licenses        "$STAGE/licenses"
chmod +x              "$STAGE/start.sh"

# Installer config. install.sh installs a named `eyas` command to ~/.local/bin
# and (on re-install) preserves .env + data/. The installer is generated from
# standalone.json so the command name / port never drift from a hand-edited
# copy. See scripts/gen-install.sh.
cp standalone.json "$STAGE/standalone.json"
bash scripts/gen-install.sh "${SCRIPT_DIR}/standalone.json" > "$STAGE/install.sh"
chmod +x "$STAGE/install.sh"
ok "install.sh + standalone.json staged"

# End-user-facing docs bundled under docs/. README.md (= STANDALONE.md) is the
# entry point; the rest are referenced from there as deeper reading. IR-SETUP
# and SHADOW-AI-SETUP back the Part 6 / Part 7 provisioning hand-offs in the
# onboarding guide — keep them shipped so those links resolve offline.
# DEPLOYMENT (Docker), USERGUIDE (per-persona feature tour), WHITEPAPER
# (conceptual overview). Internal CHANGELOG-* and docs not relevant to recipients are
# skipped.
mkdir -p "$STAGE/docs"
for d in STANDALONE IR-SETUP SHADOW-AI-SETUP USERGUIDE DEPLOYMENT WHITEPAPER; do
  if [ -f "docs/$d.md" ]; then
    cp "docs/$d.md" "$STAGE/docs/$d.md"
  fi
done

# Same NFT-tracing leak hits data/: lib/auth, lib/cost, lib/perf all reference
# `${cwd}/data/...` so the tracer copies the dev host's data/ into the bundle.
# Shipping that means recipients inherit OUR auth.json (so they see sign-in
# instead of register) and our cost-log/perf-log. Scrub unconditionally;
# start.sh recreates data/ on first launch.
rm -rf "$STAGE/data"

ok "launcher + docs staged"

# ─── Stage better-sqlite3 macOS prebuilds (multi-ABI) ────────────────────────
# Next.js standalone copies whatever `better-sqlite3/build/Release/*.node` the
# build host has. On a Linux build host that's the Linux ELF binary, which
# ENOEXECs on macOS. We stage one prebuild per supported (target, node-ABI)
# tuple under vendor/better-sqlite3-prebuilds/<target>-<abi>/, and start.sh
# picks the matching one at launch based on the recipient's `uname -m` and
# `process.versions.modules`. Source of truth: WiseLibs/better-sqlite3
# upstream Release assets — same trust chain as runtime npm.
#
# ABI map (Node major → process.versions.modules):
#   Node 22 → 127,  Node 24 → 137,  Node 26 → 147
# Node 20 (ABI 115) is intentionally NOT staged — it reached end-of-life in
# 2026 and start.sh's minimum is Node 22. Keep BSQLITE_ABIS and start.sh's
# NODE_MAJOR gate in sync: every ABI a recipient might run must be staged, or
# start.sh fails the launch with a clear error. Update both when a new LTS
# lands; old entries can stay while the upstream tarball exists.
#
# Apple Silicon only (darwin-arm64) — the fleet is fully arm64. An Intel Mac
# would ENOEXEC at launch; re-add darwin-x64 to BSQLITE_TARGETS if that fleet
# returns. start.sh selects `darwin-<arch>-<abi>` from the recipient's
# `uname -m` + `process.versions.modules`.
BSQLITE_VERSION=$(node -e "process.stdout.write(require('./node_modules/better-sqlite3/package.json').version)")
BSQLITE_TARGETS=(darwin-arm64)
BSQLITE_ABIS=(127 137 147)
# Default-dest target used when start.sh's selector is bypassed.
BSQLITE_DEFAULT_TARGET="darwin-arm64"
BSQLITE_PREBUILDS_DIR="$STAGE/vendor/better-sqlite3-prebuilds"
BSQLITE_DEFAULT_DEST="$STAGE/node_modules/better-sqlite3/build/Release/better_sqlite3.node"
if [ -f "$BSQLITE_DEFAULT_DEST" ]; then
  step "Staging better-sqlite3 prebuilds for [${BSQLITE_TARGETS[*]}] × ABIs [${BSQLITE_ABIS[*]}]…"
  mkdir -p "$BSQLITE_PREBUILDS_DIR"
  BSQLITE_TMP="$OUT_DIR/.bsqlite"
  rm -rf "$BSQLITE_TMP" && mkdir -p "$BSQLITE_TMP"

  # fetch_prebuild <github-release-path> <dest> downloads one prebuild tarball.
  # Default: straight from GitHub. internal/build.env may define its own (e.g. a
  # mirror that SHA256-verifies the cached asset) before this point.
  if ! declare -F fetch_prebuild >/dev/null; then
    fetch_prebuild() {
      echo "  WARN: fetching $(basename "$1") directly from GitHub (no mirror checksum)" >&2
      curl -sSLf -o "$2" "https://github.com/$1"
    }
  fi

  for target in "${BSQLITE_TARGETS[@]}"; do
    for abi in "${BSQLITE_ABIS[@]}"; do
      asset="better-sqlite3-v${BSQLITE_VERSION}-node-v${abi}-${target}.tar.gz"
      release_path="WiseLibs/better-sqlite3/releases/download/v${BSQLITE_VERSION}/${asset}"
      work="$BSQLITE_TMP/${target}-${abi}"
      mkdir -p "$work"

      if ! fetch_prebuild "$release_path" "$work/prebuild.tar.gz"; then
        echo "  ERROR: failed to fetch ${target} ABI ${abi} prebuild (${release_path})" >&2
        exit 1
      fi

      tar -xzf "$work/prebuild.tar.gz" -C "$work"
      if [ -f "$work/build/Release/better_sqlite3.node" ]; then
        dest_dir="$BSQLITE_PREBUILDS_DIR/${target}-${abi}"
        mkdir -p "$dest_dir"
        cp "$work/build/Release/better_sqlite3.node" "$dest_dir/better_sqlite3.node"
      else
        echo "  ERROR: prebuild tarball for ${target} ABI ${abi} did not contain the expected .node file" >&2
        exit 1
      fi
    done
  done
  # Also swap the default location with the lowest-ABI prebuild for the default
  # target so a recipient on the matching Node version boots even if start.sh's
  # selector is bypassed.
  cp "$BSQLITE_PREBUILDS_DIR/${BSQLITE_DEFAULT_TARGET}-${BSQLITE_ABIS[0]}/better_sqlite3.node" "$BSQLITE_DEFAULT_DEST"
  rm -rf "$BSQLITE_TMP"
fi

# ─── Pre-download falcon-mcp wheels for offline install ───────────────────────
# End-user Macs may be on networks (browser isolation, corp proxies) that block
# CLI egress to PyPI. Bundling the wheels lets start.sh install offline. Skipped
# if uv is absent on the build host.
WHEELS_PYTHON_VERSION="${WHEELS_PYTHON_VERSION:-3.12}"
# pip platform tag for the target Mac. Apple Silicon: macosx_11_0_arm64.
# Intel: macosx_10_9_x86_64. Override via WHEELS_PIP_PLATFORM.
WHEELS_PIP_PLATFORM="${WHEELS_PIP_PLATFORM:-macosx_11_0_arm64}"
# pip resolves from PyPI unless internal/build.env (sourced above) exported a
# mirror index + constraints. An unreachable index silently yields "Could not
# find a version … (from versions: none)" and the build aborts below rather
# than shipping a non-self-sufficient bundle.
if command -v python3 >/dev/null 2>&1; then
  step "Building falcon-mcp wheel from pinned commit (${PIN_FALCON_MCP_REF:0:12}, python ${WHEELS_PYTHON_VERSION}, ${WHEELS_PIP_PLATFORM})…"
  mkdir -p "$STAGE/vendor/falcon-mcp-wheels"
  # The MCP server (eyas-mcp) is sourced from its git repo at a pinned commit (not
  # PyPI) so dev (uvx --from git+…@ref) and the bundle build the exact same tree
  # — single source of truth in versions.json. We build the pure-python wheel
  # locally, then download its transitive deps as platform-targeted wheels so
  # the target Mac can install offline (--no-index in start.sh).
  TMPVENV="$OUT_DIR/.pipvenv"
  # Prefer a >=3.11 interpreter for the build venv: it matches the 3.12 wheel
  # target and satisfies falcon-mcp's requires-python. Bare `python3` is often
  # the macOS system 3.9 (Homebrew installs versioned names like python3.12),
  # so probe explicitly. Override with WHEELS_PYTHON=/path/to/pythonX.YY.
  PY_BUILD="${WHEELS_PYTHON:-}"
  if [ -z "$PY_BUILD" ]; then
    for cand in python3.13 python3.12 python3.11 python3; do
      if command -v "$cand" >/dev/null 2>&1; then PY_BUILD="$cand"; break; fi
    done
  fi
  "$PY_BUILD" -m venv "$TMPVENV" >/dev/null
  FM_CLONE="$OUT_DIR/falcon-mcp-src"
  FM_OK=1
  # Full clone + checkout (not --depth 1): the pinned SHA may not be branch HEAD.
  if ! git clone --quiet "$PIN_FALCON_MCP_GIT" "$FM_CLONE" 2>/dev/null; then
    FM_OK=0
  elif ! git -C "$FM_CLONE" checkout --quiet "$PIN_FALCON_MCP_REF" 2>/dev/null; then
    FM_OK=0
  fi
  if [ "$FM_OK" = "1" ]; then
    # Build the pure-python wheel with the PEP 517 frontend. `pip wheel` would
    # reject the build whenever the build-host interpreter is older than the
    # package's requires-python (>=3.11); `python -m build` produces the same
    # py3-none-any wheel regardless of the build interpreter.
    if ! "$TMPVENV/bin/pip" install --quiet build >/dev/null 2>&1 \
       || ! "$TMPVENV/bin/python" -m build --wheel \
              --outdir "$STAGE/vendor/falcon-mcp-wheels" "$FM_CLONE" >/dev/null 2>&1; then
      FM_OK=0
    fi
  fi
  if [ "$FM_OK" = "1" ]; then
    # Pull the runtime deps the built wheel declares (Requires-Dist, minus extras)
    # so we mirror exactly what the pinned commit needs — no hardcoded dep list.
    FM_WHEEL=$(find "$STAGE/vendor/falcon-mcp-wheels" -name "${PIN_FALCON_MCP_PKG//-/_}-*.whl" | head -1)
    FM_DEPS=()
    while IFS= read -r dep; do
      [ -n "$dep" ] && FM_DEPS+=("$dep")
    done < <("$TMPVENV/bin/python" - "$FM_WHEEL" <<'PY'
import sys, zipfile
from email.parser import Parser
z = zipfile.ZipFile(sys.argv[1])
meta = next(n for n in z.namelist() if n.endswith(".dist-info/METADATA"))
msg = Parser().parsestr(z.read(meta).decode("utf-8", "replace"))
for r in msg.get_all("Requires-Dist") or []:
    # Drop optional-extra deps (only ship runtime deps for offline install).
    if "extra ==" in r or "; extra" in r:
        continue
    spec = r.split(";")[0].strip()
    if spec:
        print(spec)
PY
)
    if [ "${#FM_DEPS[@]}" -gt 0 ] \
       && "$TMPVENV/bin/pip" download "${FM_DEPS[@]}" \
            --python-version "$WHEELS_PYTHON_VERSION" \
            --platform "$WHEELS_PIP_PLATFORM" \
            --only-binary=:all: \
            --dest "$STAGE/vendor/falcon-mcp-wheels" >/dev/null; then
      COUNT=$(find "$STAGE/vendor/falcon-mcp-wheels" -type f \( -name '*.whl' -o -name '*.tar.gz' \) | wc -l | tr -d ' ')
      ok "falcon-mcp wheel built from ${PIN_FALCON_MCP_REF:0:12}; wheels staged ($COUNT files)"
    else
      echo "  ERROR: falcon-mcp dependency download failed — the bundle would not be self-sufficient." >&2
      echo "         pip could not resolve falcon-mcp's deps from \$PIP_INDEX_URL (${PIP_INDEX_URL})." >&2
      rm -rf "$STAGE/vendor/falcon-mcp-wheels"
      exit 1
    fi
  else
    echo "  ERROR: falcon-mcp wheel build failed (clone/checkout/build of ${PIN_FALCON_MCP_GIT}@${PIN_FALCON_MCP_REF:0:12})." >&2
    echo "         The bundle would not be self-sufficient — aborting rather than shipping an online-fallback build." >&2
    rm -rf "$STAGE/vendor/falcon-mcp-wheels"
    exit 1
  fi
  rm -rf "$FM_CLONE"
  rm -rf "$TMPVENV"
else
  echo "  ERROR: python3 not found on build host — cannot pre-build the offline wheels." >&2
  echo "         A self-sufficient bundle requires the wheels; install python3 and re-run." >&2
  exit 1
fi

# ─── Write BUILD-INFO.txt + build-info.json ──────────────────────────────────
# BUILD-INFO.txt is human-readable (end users + support can `cat` it).
# build-info.json is read by the app at runtime and surfaced on /status so the
# audience can answer "what version am I running?" from the UI.
step "Writing BUILD-INFO…"
cat > "$STAGE/BUILD-INFO.txt" <<EOF
falcon-mcp frontend ${VERSION}
Built: ${BUILD_TIMESTAMP}
Git:   ${GIT_SHA}${GIT_DIRTY}
Node:  ${NODE_VERSION}

Pinned upstream versions:
  ${PIN_FALCON_MCP_PKG}             ${PIN_FALCON_MCP}

MCP server source: ${PIN_FALCON_MCP_GIT}
MCP server commit: ${PIN_FALCON_MCP_REF}

Wheel target: python ${WHEELS_PYTHON_VERSION} / ${WHEELS_PIP_PLATFORM}
EOF
cat > "$STAGE/build-info.json" <<EOF
{
  "buildKind": "standalone",
  "appVersion": "${VERSION}",
  "builtAt": "${BUILD_TIMESTAMP}",
  "gitSha": "${GIT_SHA}${GIT_DIRTY}",
  "nodeVersion": "${NODE_VERSION}",
  "pins": {
    "mcp-server": "${PIN_FALCON_MCP}"
  },
  "mcpServer": {
    "package": "${PIN_FALCON_MCP_PKG}",
    "git": "${PIN_FALCON_MCP_GIT}",
    "ref": "${PIN_FALCON_MCP_REF}"
  },
  "wheelTarget": {
    "pythonVersion": "${WHEELS_PYTHON_VERSION}",
    "platform": "${WHEELS_PIP_PLATFORM}"
  },
  "deploymentLock": {
    "gatewayOnly": ${GATEWAY_ONLY},
    "forcedGatewayUrl": ${GATEWAY_LITERAL}
  }
}
EOF
ok "BUILD-INFO.txt + build-info.json written"

step "Zipping…"
rm -f "$ZIP_PATH"
if command -v zip >/dev/null 2>&1; then
  ( cd "$OUT_DIR" && zip -qr "$ZIP_PATH" "${BUNDLE_NAME}" )
else
  # Fallback for hosts without `zip` (e.g. minimal Linux). Python's zipfile
  # produces an identical archive end users can `unzip` on macOS.
  ( cd "$OUT_DIR" && python3 -m zipfile -c "$ZIP_PATH" "${BUNDLE_NAME}" )
fi
rm -rf "$OUT_DIR"

# Remove the production build output so it doesn't poison the dev server's
# chunk cache (next dev and next build write to the same .next/ directory).
rm -rf "${SCRIPT_DIR}/.next"

SIZE=$(du -h "$ZIP_PATH" | cut -f1)
echo ""
echo -e "  ${GREEN}${BOLD}Done.${RESET}  ${DIM}→${RESET}  ${BOLD}${ZIP_PATH}${RESET}  (${SIZE})"
echo ""
echo "  Distribute this zip. End user runs:"
echo "    unzip ${BUNDLE_NAME}.zip"
echo "    cd ${BUNDLE_NAME}"
echo "    bash install.sh      # installs the 'eyas' command to ~/.local/bin"
echo "    eyas                 # start (background, opens browser); eyas stop|status|logs"
echo ""
echo "  (Or run ./start.sh in the folder for a one-off foreground launch without installing.)"
echo ""
echo "  install.sh/start.sh auto-create .env and generate AUTH_SESSION_SECRET on"
echo "  first run. Falcon + Anthropic credentials are collected in-browser via"
echo "  /register. To upgrade later, run a newer bundle's install.sh (keeps .env + data/)."
echo ""
