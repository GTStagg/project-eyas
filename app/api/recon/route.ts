import { NextResponse } from "next/server";
import { runAgentLoop } from "@/lib/chat/agent-loop";
import { streamAgent } from "@/lib/chat/stream-agent";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

type Kind = "domain" | "email";
type Body = { query?: string; kind?: Kind };

// Strict client-side regexes — server-side enforcement happens in the
// extras sidecar, but rejecting obvious garbage early gives a better UX.
const DOMAIN_RX = /^[a-z0-9][a-z0-9.\-]{0,253}$/;
const EMAIL_RX = /^[a-z0-9._%+\-]+@[a-z0-9.\-]+$/;

function buildPrompt(query: string, kind: Kind): string {
  const today = new Date().toISOString().slice(0, 10);
  const isDomain = kind === "domain";
  const subjectLabel = isDomain ? "domain" : "email address";

  return [
    `You are producing a RECON EXPOSURE report for a CrowdStrike Falcon tenant administrator. The user supplied a single ${subjectLabel} and wants one screen that answers: how many times does this surface across the dark web / criminal marketplaces / Telegram / paste sites, are our credentials in known breaches, what are we already monitoring, and what should we do.`,
    "",
    `Today is ${today} (UTC).`,
    `Subject: \`${query}\` (kind: ${kind})`,
    "",
    "DATA GATHERING — fan these out in parallel up front:",
    `- \`extras_recon_preview_corpus_search\` — THE PRIMARY DATA SOURCE for this report. Queries the full Recon data lake (criminal marketplaces, forums, GitHub paste-leaks, Telegram channels, social media). Pass query=${JSON.stringify(query)}, kind=${JSON.stringify(kind)}. Returns total hits + breakdown by channel + top sites. Aggregate counts only — raw items are not returned by CrowdStrike.`,
    `- \`extras_recon_search_exposed_records\` — credential-exposure corpus (leaked passwords from breach dumps). Pass query=${JSON.stringify(query)}, kind=${JSON.stringify(kind)}, limit=100. This is the only path that returns actual leaked usernames/emails.`,
    `- \`extras_recon_search_notifications\` — notifications already generated by tenant Recon rules. Pass q=${JSON.stringify(query)}, limit=50. Tenant-scoped — a value of zero here just means no rule was set up to watch this subject.`,
    "- `extras_recon_list_rules` — list active monitoring rules so we can tell the operator whether the subject is already covered (and skip proposing redundant new rules). Pass limit=100.",
    isDomain
      ? `- \`falcon_search_iocs\` — check the tenant custom IOC list for this domain so we don't propose an IOC-add when one already exists. Filter: type:'domain'+value:${JSON.stringify(query)}.`
      : "",
    "",
    "After the initial fan-out, do not loop. Write the report.",
    "",
    "SCOPE HANDLING: If `extras_recon_preview_corpus_search` (or any other tool) returns `scope_pending: true`, emit ONLY a single sentence: 'Required Falcon API scope (`Falcon Adversary Intelligence Recon : read`) is not yet granted on this tenant API client.' Stop. Do not produce the rest of the report.",
    "",
    "Sections — produce all of them in this exact order. Use H2 (##) for each:",
    "",
    "## Headline",
    `One sentence. Lead with the corpus hit count from extras_recon_preview_corpus_search. Format: "<N> mentions of \`${query}\` across the Recon corpus, plus <M> exposed credential record(s); <existing|no> tenant coverage." If preview hits is zero, say plainly: "No mentions of \`${query}\` observed in the Recon corpus."`,
    "",
    "## Recon corpus breakdown",
    "Use the channel + site breakdown from extras_recon_preview_corpus_search.",
    "Render two compact tables side-by-side or stacked:",
    "1. **By channel** — Channel | Count. Channel labels include criminal_marketplace, forum, public_repo, chat_medium, social_media. Translate machine labels to human-readable: 'Criminal marketplaces', 'Forums', 'Public repos (GitHub paste-leaks)', 'Chat platforms (Telegram, Discord)', 'Social media'.",
    "2. **Top sites** — Site | Count, capped at the top 10 by count.",
    "Below the tables, one short sentence interpreting the shape: e.g., 'Concentrated on criminal marketplaces (russianmarket) — typical for a financial brand being trafficked for fraud.' If total is zero, omit tables and say 'No mentions in the corpus.'",
    "",
    "## Exposed credentials",
    "If extras_recon_search_exposed_records returned items, render a table: Email | Source category | Site | Exposed | Credential status. Truncate to the 10 most recent. Below: distinct email count, oldest/newest exposure dates. If zero items, say 'No exposed credentials for this subject in the breach corpus.'",
    "",
    "## Existing tenant coverage",
    `From extras_recon_list_rules, identify any active rule whose name, topic, or filter references \`${query}\` (or its registrable domain for emails). Render a small table: Rule name | Topic | Status | Priority | Updated. If none, say 'No existing Recon rule covers this subject.'`,
    "Then add a one-line note about extras_recon_search_notifications: how many notifications the tenant already received for this subject (zero is normal when no rule exists).",
    isDomain
      ? "Then mention whether the custom IOC list already has an entry for the domain (from falcon_search_iocs). If yes: action / source / expiration. If no: 'Not on the custom IOC list.'"
      : "",
    "",
    "## Recommended actions",
    "Pick the pattern that fits the evidence. Be decisive — one or two recommendations max, not a checklist:",
    "- High corpus hit count (50+) + no existing rule → 'Stand up a Recon monitoring rule for this subject so each new hit surfaces as a notification.' Recommend topic based on kind (SA_DOMAIN for domains, SA_EMAIL for emails, SA_CUSTOM for keywords/brand). Note: monitoring rules generate notifications; without one, future hits go unsurfaced even though they exist in the corpus.",
    "- Exposed credentials present → 'Force password reset for the exposed accounts.' List the affected emails (cap at 10).",
    isDomain
      ? "- Domain consistently mentioned across criminal marketplaces + not on custom IOC list + Falcon Intel rates it malicious → 'Add a custom IOC with `detect` action.' Suggest the falcon_add_ioc arguments. Do NOT call the tool — just propose. (Domain IOCs are detect-only at the Falcon API — `prevent` is rejected; that's a DNS/NGFW concern, not the endpoint sensor.)"
      : "",
    "- Corpus shows hits but tenant rule already covers the subject → 'Coverage in place. Audit the existing rule's recent notifications instead of creating a new one.'",
    "- Zero hits + zero exposures + no existing rule → 'No action. Optionally create a baseline monitoring rule.'",
    "",
    "Do not propose redundant coverage. If the IOC list / a Recon rule / Falcon Intel already covers the subject, call that out instead of proposing a duplicate.",
    "",
    "Style:",
    "- Markdown only. H2 headings.",
    "- Tables for the structured sections.",
    "- Be terse and decisive. No filler.",
    "- If a section has no data, still include the heading with a one-line note.",
    "",
    "OUTPUT DISCIPLINE:",
    "- Output NOTHING between tool calls. Zero text.",
    "- Make all tool calls in parallel, then write the report ONCE.",
    "- The very first text token you emit must be the Headline H2.",
    "",
    "Citations:",
    "- Tool calls are numbered 1, 2, 3, … in call order.",
    "- End facts with [N] referencing the call number.",
    "- Do not invent citations.",
  ]
    .filter(Boolean)
    .join("\n");
}

export async function POST(request: Request) {
  const body = (await request.json().catch(() => ({}))) as Body;
  const query = (body.query ?? "").trim().toLowerCase();
  const kind: Kind = body.kind === "email" ? "email" : "domain";
  if (!query) {
    return NextResponse.json(
      { ok: false, error: "query required" },
      { status: 400 },
    );
  }
  const ok = kind === "domain" ? DOMAIN_RX.test(query) : EMAIL_RX.test(query);
  if (!ok) {
    return NextResponse.json(
      { ok: false, error: `invalid ${kind}: ${query}` },
      { status: 400 },
    );
  }

  return streamAgent(async ({ mcp, extras, emit, signal }) => {
    await runAgentLoop({
      signal,
      mcp,
      extrasMcp: extras,
      systemPrompt: buildPrompt(query, kind),
      initialMessages: [
        { role: "user", content: `Recon lookup: ${query} (kind: ${kind})` },
      ],
      emit,
      maxTokensPerTurn: 8192,
      maxIterations: 12,
      surface: "recon",
    });
  });
}
