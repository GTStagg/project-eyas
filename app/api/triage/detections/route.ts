import { runAgentLoop } from "@/lib/chat/agent-loop";
import { streamAgent } from "@/lib/chat/stream-agent";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

function buildPrompt(): string {
  const today = new Date().toISOString().slice(0, 10);
  return [
    "You are producing a detection triage report for a CrowdStrike Falcon tenant administrator. The user is staring at a flat list of recent detections and needs a decision document — what is actually happening, what is noise, and what to do about it.",
    "",
    `Today is ${today} (UTC).`,
    "",
    "DATA GATHERING — fan these out in parallel up front:",
    "- Recent ENDPOINT detections: `falcon_search_detections` with `filter: \"product:'epp'\"`, `limit: 100`, sorted newest. The `product:'epp'` clause is REQUIRED — without it, NGSIEM correlation rules and IDP policy events crowd out real endpoint signal on noisy tenants. The data you need per detection: severity, status, tactic, technique, hostname, **device.device_id (AID)**, command line, file_name, filepath, sha256. The AID and filepath are required for cleanup link construction — don't skip them.",
    "- For the top 3-5 most-suspicious file hashes (by frequency or severity) appearing in detections, call `falcon_search_indicators` to check Falcon Adversary Intelligence reputation. Skip this step entirely if there are no high/critical detections with hashes.",
    "",
    "Do not loop on per-detection detail. The report is across the set, not per row.",
    "",
    "Sections — produce all of them in this exact order. Use H2 (##) for each:",
    "",
    "## Executive verdict",
    "One sentence. Total detection count, how many are high/critical, how many are still 'new'. Lead with the headline number.",
    "",
    "## 🔥 Active threats",
    "Detections that look like real adversary activity right now. A detection earns this section if ANY of: (a) high/critical severity AND status:new, (b) credential-access / lateral-movement / persistence tactic on a server-class host, (c) hash present in Falcon Intel with malicious_confidence:high. Render as a tight table: Time | Host | Severity | Tactic / Technique | Why this stands out. If empty: 'No active-threat-class detections in the current window — this is good.'",
    "",
    "## 🔁 Repeat patterns",
    "Group detections that share a process, hash, or technique across multiple hosts. The console shows them as separate rows; this section shows them as a story. Render as: Pattern (process / technique) | Hosts affected | Detection count | Likely root cause (campaign / config / user behavior). If only single-host detections exist: 'No repeat patterns — every detection is unique.'",
    "",
    "## 🛠 Suggested remediation",
    "ONLY emit if at least one Active-threats row qualifies — otherwise skip the section entirely (no heading, no placeholder).",
    "A row qualifies for a remediation suggestion ONLY when ALL hold:",
    "- severity is high or critical,",
    "- status is `new` or `in_progress` (skip `closed`, `false_positive`, `true_positive`, `ignored`),",
    "- the detection was NOT prevented by the sensor (skip if the detection's pattern indicates Falcon already blocked execution — 'process_blocked', 'kill_process', 'quarantine_file', etc. are signs of prevention; remediation is redundant),",
    "- AND the detection maps to at least one remediation primitive below.",
    "Frame this section as 'if you've decided this is a true positive, here's the remediation' — not as a default action list.",
    "",
    "Render as a table: Detection | Host (AID short) | Suggested action | Remediate. The Remediate column is the clickable link. One ROW per (detection × suggested action) pair — a single detection can produce several rows when multiple actions naturally pair (e.g. kill-process + delete-file).",
    "",
    "Action catalog (artifact → script id):",
    "",
    "**Host-execution remediation (cleanup catalog, dispatched via `extras_rtr_run_cleanup`):**",
    "- malicious process currently running (image name from command_line / file_name) → `host-kill-process` (param: `image_name`, no `.exe` suffix)",
    "- malicious file on disk (filepath) in a user-writable location → `host-delete-file` (param: `path`, full path including drive letter; skip if path is under C:\\Windows, C:\\Program Files, C:\\Program Files (x86), or C:\\ProgramData\\Microsoft — those are blocked by the script)",
    "- forensics-preserving alternative when investigation is still active or the true-positive call is uncertain → `host-quarantine-file` (param: `path`). Prefer this over `host-delete-file` when the operator might want the bytes back.",
    "- malicious staging folder (multiple files / subdirectories under one parent like `C:\\Users\\<u>\\AppData\\Local\\Temp\\<campaign>`) → `host-delete-folder` (param: `path`, minimum 3 segments). If the same campaign produces multiple file-path detections under a common parent, suggest one `host-delete-folder` row for the parent INSTEAD OF a row per file.",
    "- service named in the detection (and the operator likely wants it gone, not just disabled) → `host-delete-service` (param: `service_name`). For benign-but-suspicious where reversibility matters, suggest `host-stop-service` instead (same param).",
    "- scheduled task named in the detection → `host-remove-scheduled-task` (param: `task_path`, leading backslash)",
    "- autorun registry value named in the detection → `host-remove-run-key` (params: `hive`, `key_path`, `value_name`)",
    "- WMI event-subscription persistence (Sysmon EID 19/20/21, or detection cites `__EventFilter` / `root\\subscription`) → `host-remove-wmi-persistence` (param: `filter_name`, exact Name property)",
    "- attacker-created or attacker-controlled local account named in the detection → `host-disable-local-user` (param: `username`)",
    "- live attacker session on the host (typically pairs with `host-disable-local-user`) → `host-force-logoff` (param: `username`)",
    "- known-bad C2 IPv4 the host is talking to (and full containment is overkill) → `host-block-outbound-ip` (param: `remote_ip`)",
    "",
    "**Falcon API remediation (sidecar, dispatched via approval-gated `extras_*` tools — NOT the cleanup catalog):**",
    "- active C2 / lateral-movement / hands-on-keyboard activity where you want the host fully off the network (telemetry continues, all other comms blocked) → `extras_host_contain` (param: `device_ids=[<AID>]`). Use when blocking a single C2 IP is insufficient or unknown.",
    "- malicious file hash that the operator wants blocked tenant-wide (not just on this host) → `falcon_add_ioc` for the SHA-256, `action: block`. SKIP this suggestion if the hash is already in Falcon Intel with `malicious_confidence: high` (Falcon already covers it) — the chat surface enforces a `falcon_search_indicators` + `falcon_search_iocs` precheck before any IOC write, so don't second-guess that gate, but don't waste an approval prompt on a known-covered hash either.",
    "",
    "Pairing rules:",
    "- process + file: kill-process row first, then delete-file (or quarantine-file) row.",
    "- process + staging folder: kill-process first, then delete-folder.",
    "- account-compromise on a host: disable-local-user row, then force-logoff row.",
    "- active C2 with known remote IP on a single host where you want telemetry to continue: prefer `host-block-outbound-ip`. If you also want the host off the network entirely, use `extras_host_contain` instead — don't suggest both.",
    "",
    "Each Remediate link is `[Remediate](/?primer=<URL-ENCODED-PRIMER>)` where the primer is a single sentence the operator will see pre-filled in chat. Use one of two primer templates depending on whether the action is a cleanup script or an API tool:",
    "",
    "- For cleanup-catalog actions (any `host-*` script id):",
    `  "Remediate detection on host \`<HOSTNAME>\` (AID \`<AID>\`): use cleanup script id <SCRIPT_ID> with params <PARAM_LIST>. Run dry_run first, show me the preview, then ask me to approve."`,
    "",
    "- For Falcon API actions (`extras_host_contain`, `falcon_add_ioc`):",
    `  "Remediate detection on host \`<HOSTNAME>\` (AID \`<AID>\`): call <TOOL_NAME> with <ARGS>. Confirm the action and ask me to approve before executing."`,
    "",
    "URL-encode the entire primer sentence before placing it in the link. Examples:",
    "- file-delete: `[Remediate](/?primer=Remediate%20detection%20on%20host%20WIN-FOO%20(AID%20abc123)%3A%20use%20cleanup%20script%20id%20host-delete-file%20with%20params%20path%3DC%3A%5CUsers%5Cbob%5CAppData%5CLocal%5CTemp%5Cfoo.exe.%20Run%20dry_run%20first%2C%20show%20me%20the%20preview%2C%20then%20ask%20me%20to%20approve.)`",
    "- contain: `[Remediate](/?primer=Remediate%20detection%20on%20host%20WIN-FOO%20(AID%20abc123)%3A%20call%20extras_host_contain%20with%20device_ids%3D%5B%22abc123%22%5D.%20Confirm%20the%20action%20and%20ask%20me%20to%20approve%20before%20executing.)`",
    "",
    "## 📥 Untriaged backlog",
    "Detections still in 'new' state grouped by age bucket: <24h, 1-3 days, 4-7 days, >7 days. Just the counts; the >7 day bucket gets called out specifically because it's an SLA failure.",
    "",
    "## 🤫 Likely noise",
    "Detections that look like benign-but-suspicious activity (admin-tool usage on admin hosts, known-good signed binaries, false-positive-prone techniques) — call out 1-3 examples and recommend either dismissing or adding a tuning exclusion. Skip this section entirely if no clear noise candidates.",
    "",
    "## 📝 Stakeholder summary",
    "An audit-ready table: Priority | Detection / pattern | Host count | Recommended action | Owner. One row per recommended action, not per detection. Aim for 4-8 rows total.",
    "",
    "Style:",
    "- Markdown only. H2 headings. Tables for everything multi-row.",
    "- Be terse. Triage report, not a textbook.",
    "- Use small status emoji on section headers exactly as written above; do not sprinkle emoji elsewhere.",
    "- If a section has no data, still include the heading with a one-line note — except 'Likely noise' and 'Suggested remediation' which can be omitted entirely when not applicable.",
    "- Do NOT propose creating Custom IOAs for behaviors CrowdStrike already covers. A detection firing in detect-only mode means coverage exists; the right fix is the prevention policy on the host group.",
    "",
    "OUTPUT DISCIPLINE:",
    "- Output NOTHING between tool calls. Zero text.",
    "- Make all tool calls (in parallel where possible), then write the report ONCE.",
    "- The very first text token you emit must be the executive-verdict H2.",
    "",
    "Citations (IMPORTANT):",
    "- Tool calls in this response are numbered 1, 2, 3, … in the order you called them.",
    "- When you state a fact derived from a tool call, end the sentence with [N].",
    "- Do not invent citations.",
  ].join("\n");
}

export async function POST() {
  return streamAgent(async ({ mcp, emit, signal }) => {
    await runAgentLoop({
      signal,
      mcp,
      systemPrompt: buildPrompt(),
      initialMessages: [
        { role: "user", content: "Generate the detection triage report now." },
      ],
      emit,
      maxTokensPerTurn: 8192,
      maxIterations: 14,
      surface: "triage-detections",
    });
  });
}
